export function translateAdmin(locale, key, variables = {}) {
  const dictionary = adminTranslations[locale] || adminTranslations.vi;
  const template = dictionary[key] ?? adminTranslations.vi[key] ?? key;
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
